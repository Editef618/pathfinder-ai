export const I18N: Record<LangCode, Dict> = { en, ko, ja, es, fr, zh };

type Vars = Record<string, string | number>;

function interpolate(s: string, vars?: Vars) {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
}

type Ctx = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  /** UI string by key. */
  t: (k: string, vars?: Vars) => string;
  /** Demo-content string: localises the English source text where available. */
  tx: (text: string) => string;
  /** Skill status label. */
  ts: (status: string) => string;
};
const LangContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<LangCode>("en");
  const t = useCallback(
    (k: string, vars?: Vars) => interpolate(I18N[lang][k] ?? en[k] ?? k, vars),
    [lang],
  );
  const tx = useCallback((text: string) => CONTENT[lang]?.[text] ?? text, [lang]);
  const ts = useCallback(
    (status: string) => {
      const key = `status_${status.toLowerCase()}`;
      return I18N[lang][key] ?? en[key] ?? status;
    },
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t, tx, ts }), [lang, t, tx, ts]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used inside LanguageProvider");
  return ctx;
}
